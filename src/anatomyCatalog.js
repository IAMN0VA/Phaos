export function regionFamily(region){
  if(region === 'WHOLE_BODY') return null;
  return REGION_FAMILIES[region] || [region];
}

export function anatomyMatchesRegion(item, region){
  if(region === 'UNKNOWN') return true;
  if(region === 'WHOLE_BODY') return !item.regions.includes('UNKNOWN');
  const family = new Set(regionFamily(region));
  return item.regions.some(r => family.has(r));
}
